#!/usr/bin/env node
/**
 * Builds responsive web variants of the resort's own photographs.
 *
 *   npm run images
 *
 * - Reads originals from the directory in scripts/image-catalog.json (read-only;
 *   originals are never moved, modified or overwritten).
 * - Writes AVIF + WebP variants to apps/web/public/images/resort/<category>/
 *   at widths up to (never above) the original width.
 * - For images flagged `enhanceTo`, writes a separate, clearly named
 *   "<slug>-enhanced-<w>" variant: a Lanczos3 upscale with mild sharpening.
 *   This is interpolation, not AI detail recovery; it only softens the
 *   pixelation of 1024 px sources on large hero displays.
 * - Writes apps/web/src/content/image-manifest.json for the frontend and
 *   supabase/seed.gallery.sql for the database seed.
 */
import { mkdir, readFile, writeFile, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(await readFile(path.join(root, 'scripts/image-catalog.json'), 'utf8'));
const sourceDir = path.resolve(root, process.env.RESORT_PHOTOS_DIR ?? catalog.sourceDir);
const outRoot = path.join(root, 'apps/web/public/images/resort');
const WIDTHS = [480, 768, 1024];

const manifest = {};
const sqlRows = [];
let order = 0;

for (const entry of catalog.images) {
  const src = path.join(sourceDir, entry.file);
  await access(src);
  const input = sharp(src, { failOn: 'error' }).rotate(); // honour EXIF orientation
  const meta = await input.metadata();
  const oriented = meta.orientation && meta.orientation >= 5;
  const width = oriented ? meta.height : meta.width;
  const height = oriented ? meta.width : meta.height;

  const dir = path.join(outRoot, entry.category);
  await mkdir(dir, { recursive: true });
  const widths = [...new Set([...WIDTHS.filter((w) => w < width), width])].sort((a, b) => a - b);

  for (const w of widths) {
    const resized = input.clone().resize({ width: w, withoutEnlargement: true });
    await resized.clone().webp({ quality: 80, effort: 5 }).toFile(path.join(dir, `${entry.slug}-${w}.webp`));
    await resized.clone().avif({ quality: 55, effort: 5 }).toFile(path.join(dir, `${entry.slug}-${w}.avif`));
  }

  let enhanced = null;
  if (entry.enhanceTo && entry.enhanceTo > width) {
    const w = entry.enhanceTo;
    const up = input.clone().resize({ width: w, kernel: 'lanczos3' }).sharpen({ sigma: 0.6, m1: 0.5, m2: 1.5 });
    await up.clone().webp({ quality: 82, effort: 5 }).toFile(path.join(dir, `${entry.slug}-enhanced-${w}.webp`));
    await up.clone().avif({ quality: 58, effort: 5 }).toFile(path.join(dir, `${entry.slug}-enhanced-${w}.avif`));
    enhanced = { width: w, method: 'lanczos3 upscale + mild unsharp mask (interpolation, not AI)' };
  }

  const base = `/images/resort/${entry.category}/${entry.slug}`;
  manifest[entry.slug] = {
    src: base,
    category: entry.category,
    width,
    height,
    widths,
    enhanced,
    alt: entry.alt,
    focal: entry.focal ?? '50% 50%',
    people: Boolean(entry.people),
    source: entry.file,
  };

  const esc = (s) => s.replaceAll("'", "''");
  const note = entry.people ? "'Shows identifiable people — confirm consent before publishing.'" : 'null';
  sqlRows.push(
    `  ('${base}', '${entry.category}', '${esc(entry.alt)}', ${width}, ${height}, ${order++ * 10}, ${!entry.people}, ${note})`,
  );
  console.log(`✓ ${entry.slug.padEnd(24)} ${width}×${height}  → ${widths.join(', ')}${enhanced ? ` (+enhanced ${enhanced.width})` : ''}`);
}

// Social sharing image (1200×630) cropped from the hero photograph.
const hero = catalog.images[0];
await sharp(path.join(sourceDir, hero.file))
  .rotate()
  .resize(1200, 630, { fit: 'cover', position: 'attention', kernel: 'lanczos3' })
  .jpeg({ quality: 82, mozjpeg: true })
  .toFile(path.join(root, 'apps/web/public/og-image.jpg'));

await mkdir(path.join(root, 'apps/web/src/content'), { recursive: true });
await writeFile(
  path.join(root, 'apps/web/src/content/image-manifest.json'),
  `${JSON.stringify({ categories: catalog.categories, images: manifest }, null, 2)}\n`,
);
await writeFile(
  path.join(root, 'supabase/seed.gallery.sql'),
  `-- Generated by scripts/optimize-images.mjs — do not edit by hand.\n` +
    `insert into public.gallery_images (image_path, category, alt_text, width, height, display_order, is_published, admin_note) values\n` +
    `${sqlRows.join(',\n')}\non conflict (image_path) do nothing;\n`,
);
console.log(`\n${Object.keys(manifest).length} images processed. Excluded: ${catalog.excluded.map((e) => e.file).join(', ')}`);
